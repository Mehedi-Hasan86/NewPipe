package org.schabi.newpipe.download.playlist

import android.os.Bundle
import android.view.LayoutInflater
import android.view.View
import android.view.ViewGroup
import android.widget.AdapterView
import android.widget.ArrayAdapter
import android.widget.CheckBox
import android.widget.Spinner
import androidx.fragment.app.DialogFragment
import androidx.lifecycle.ViewModelProvider
import org.schabi.newpipe.R
import org.schabi.newpipe.databinding.SheetPlaylistBatchOptionsBinding

/**
 * Global download options for the playlist batch screen (STEP 2).
 * Edits [PlaylistDownloadOptions], persists them via the shared ViewModel.
 * The "Start download" button stays unimplemented until STEP 3.
 */
class PlaylistBatchOptionsSheet : DialogFragment() {

    companion object {
        private val QUALITIES = listOf(
            "144p", "240p", "360p", "480p", "720p", "720p60",
            "1080p", "1080p60", "1440p", "1440p60",
            "2160p", "2160p60", "4320p"
        )

        fun newInstance(): PlaylistBatchOptionsSheet {
            return PlaylistBatchOptionsSheet()
        }
    }

    private var _binding: SheetPlaylistBatchOptionsBinding? = null
    private val binding get() = _binding!!

    private lateinit var viewModel: PlaylistBatchViewModel
    private lateinit var working: MutablePlaylistOptions
    private var initializing = true
    private val subtitleCheckBoxes = mutableListOf<CheckBox>()

    /** Mutable draft edited by the widgets; copied back on save. */
    private data class MutablePlaylistOptions(
        var mode: PlaylistBatchMode = PlaylistBatchMode.VIDEO,
        var targetResolution: String = PlaylistDownloadOptions.DEFAULT_TARGET_RESOLUTION,
        var videoContainer: PlaylistVideoContainer = PlaylistVideoContainer.MP4,
        var fallbackToBest: Boolean = true,
        var audioContainer: PlaylistAudioContainer = PlaylistAudioContainer.M4A,
        var preferHighestBitrate: Boolean = true,
        var subtitlesEnabled: Boolean = false,
        var subtitleLanguages: MutableSet<String> = mutableSetOf(),
        var preferManualSubtitles: Boolean = true,
        var includeAutoGenerated: Boolean = false,
        var preferredAudioLanguage: String = PlaylistDownloadOptions.AUDIO_LANGUAGE_ORIGINAL,
        var missingLanguageAction: MissingLanguageAction = MissingLanguageAction.USE_ORIGINAL,
        var usePlaylistSubfolder: Boolean = true,
        var filenameTemplate: String = PlaylistDownloadOptions.DEFAULT_FILENAME_TEMPLATE,
        var duplicateAction: DuplicateAction = DuplicateAction.OVERWRITE,
        var appendLanguageSuffix: Boolean = true
    ) {
        fun toImmutable(): PlaylistDownloadOptions {
            return PlaylistDownloadOptions(
                mode = mode,
                targetResolution = targetResolution,
                videoContainer = videoContainer,
                fallbackToBest = fallbackToBest,
                audioContainer = audioContainer,
                preferHighestBitrate = preferHighestBitrate,
                subtitlesEnabled = subtitlesEnabled,
                subtitleLanguages = subtitleLanguages.toList().sorted(),
                preferManualSubtitles = preferManualSubtitles,
                includeAutoGenerated = includeAutoGenerated,
                preferredAudioLanguage = preferredAudioLanguage,
                missingLanguageAction = missingLanguageAction,
                usePlaylistSubfolder = usePlaylistSubfolder,
                filenameTemplate = filenameTemplate,
                duplicateAction = duplicateAction,
                appendLanguageSuffix = appendLanguageSuffix
            )
        }
    }

    override fun onCreateView(
        inflater: LayoutInflater,
        container: ViewGroup?,
        savedInstanceState: Bundle?
    ): View {
        _binding = SheetPlaylistBatchOptionsBinding.inflate(inflater, container, false)
        return binding.root
    }

    override fun onViewCreated(view: View, savedInstanceState: Bundle?) {
        super.onViewCreated(view, savedInstanceState)
        viewModel = ViewModelProvider(requireParentFragment())[PlaylistBatchViewModel::class.java]
        viewModel.loadOptions()

        val current = viewModel.options.value ?: PlaylistDownloadOptions()
        working = MutablePlaylistOptions(
            mode = current.mode,
            targetResolution = current.targetResolution,
            videoContainer = current.videoContainer,
            fallbackToBest = current.fallbackToBest,
            audioContainer = current.audioContainer,
            preferHighestBitrate = current.preferHighestBitrate,
            subtitlesEnabled = current.subtitlesEnabled,
            subtitleLanguages = current.subtitleLanguages.toMutableSet(),
            preferManualSubtitles = current.preferManualSubtitles,
            includeAutoGenerated = current.includeAutoGenerated,
            preferredAudioLanguage = current.preferredAudioLanguage,
            missingLanguageAction = current.missingLanguageAction,
            usePlaylistSubfolder = current.usePlaylistSubfolder,
            filenameTemplate = current.filenameTemplate,
            duplicateAction = current.duplicateAction,
            appendLanguageSuffix = current.appendLanguageSuffix
        )

        setupMode()
        setupSpinners()
        setupSubtitles()
        setupNaming()

        binding.saveButton.setOnClickListener {
            working.filenameTemplate = binding.templateInput.text?.toString().orEmpty()
            working.subtitleLanguages =
                PlaylistBatchResolver.commonSubtitleLanguages.filterIndexed { index, _ ->
                    subtitleCheckBoxes.getOrNull(index)?.isChecked == true
                }.toMutableSet()
            viewModel.updateOptions(working.toImmutable())
            dismiss()
        }
        binding.cancelButton.setOnClickListener { dismiss() }

        initializing = false
        refreshSubtitleVisibility()
        refreshPreview()
    }

    override fun onDestroyView() {
        _binding = null
        subtitleCheckBoxes.clear()
        super.onDestroyView()
    }

    // ------------------------------------------------------------------

    private fun setupMode() {
        if (working.mode == PlaylistBatchMode.AUDIO_ONLY) {
            binding.modeAudioButton.isChecked = true
        } else {
            binding.modeVideoButton.isChecked = true
        }
        binding.modeGroup.setOnCheckedChangeListener { _, checkedId ->
            working.mode = if (checkedId == R.id.modeAudioButton) {
                PlaylistBatchMode.AUDIO_ONLY
            } else {
                PlaylistBatchMode.VIDEO
            }
            refreshPreview()
        }
        binding.fallbackBestCheckBox.isChecked = working.fallbackToBest
        binding.fallbackBestCheckBox.setOnCheckedChangeListener { _, checked ->
            working.fallbackToBest = checked
        }
    }

    private fun setupSpinners() {
        val qualityLabels = QUALITIES
        setSpinnerItems(
            binding.qualitySpinner,
            qualityLabels,
            QUALITIES.indexOf(working.targetResolution).coerceAtLeast(0)
        ) { position ->
            working.targetResolution = QUALITIES[position]
        }

        val videoFormats = listOf(
            getString(R.string.playlist_batch_container_mp4),
            getString(R.string.playlist_batch_container_webm_video)
        )
        val videoValues = listOf(PlaylistVideoContainer.MP4, PlaylistVideoContainer.WEBM)
        setSpinnerItems(
            binding.videoFormatSpinner,
            videoFormats,
            videoValues.indexOf(working.videoContainer).coerceAtLeast(0)
        ) { position ->
            working.videoContainer = videoValues[position]
            refreshPreview()
        }

        val audioFormats = listOf(
            getString(R.string.playlist_batch_container_m4a),
            getString(R.string.playlist_batch_container_opus)
        )
        val audioValues = listOf(PlaylistAudioContainer.M4A, PlaylistAudioContainer.OPUS)
        setSpinnerItems(
            binding.audioFormatSpinner,
            audioFormats,
            audioValues.indexOf(working.audioContainer).coerceAtLeast(0)
        ) { position ->
            working.audioContainer = audioValues[position]
            refreshPreview()
        }

        val bitrates = listOf(
            getString(R.string.playlist_batch_bitrate_highest),
            getString(R.string.playlist_batch_bitrate_lowest)
        )
        setSpinnerItems(
            binding.audioBitrateSpinner,
            bitrates,
            if (working.preferHighestBitrate) 0 else 1
        ) { position ->
            working.preferHighestBitrate = position == 0
        }

        val langCodes = listOf(PlaylistDownloadOptions.AUDIO_LANGUAGE_ORIGINAL) +
            PlaylistBatchResolver.commonAudioLanguages
        val langLabels = langCodes.map { code ->
            if (code == PlaylistDownloadOptions.AUDIO_LANGUAGE_ORIGINAL) {
                getString(R.string.playlist_batch_audio_original)
            } else {
                PlaylistBatchResolver.languageDisplayName(code)
            }
        }
        setSpinnerItems(
            binding.audioLanguageSpinner,
            langLabels,
            langCodes.indexOf(working.preferredAudioLanguage).coerceAtLeast(0)
        ) { position ->
            working.preferredAudioLanguage = langCodes[position]
            refreshPreview()
        }

        val duplicates = listOf(
            getString(R.string.playlist_batch_duplicate_overwrite),
            getString(R.string.playlist_batch_duplicate_rename),
            getString(R.string.playlist_batch_duplicate_skip)
        )
        val duplicateValues = listOf(
            DuplicateAction.OVERWRITE,
            DuplicateAction.RENAME,
            DuplicateAction.SKIP
        )
        setSpinnerItems(
            binding.duplicateSpinner,
            duplicates,
            duplicateValues.indexOf(working.duplicateAction).coerceAtLeast(0)
        ) { position ->
            working.duplicateAction = duplicateValues[position]
        }

        when (working.missingLanguageAction) {
            MissingLanguageAction.USE_ORIGINAL -> binding.missingUseOriginalButton.isChecked = true
            MissingLanguageAction.SKIP_ITEM -> binding.missingSkipButton.isChecked = true
            MissingLanguageAction.ASK_AT_END -> binding.missingAskButton.isChecked = true
        }
        binding.missingLanguageGroup.setOnCheckedChangeListener { _, checkedId ->
            working.missingLanguageAction = when (checkedId) {
                R.id.missingSkipButton -> MissingLanguageAction.SKIP_ITEM
                R.id.missingAskButton -> MissingLanguageAction.ASK_AT_END
                else -> MissingLanguageAction.USE_ORIGINAL
            }
        }
    }

    private fun setupSubtitles() {
        binding.subtitlesSwitch.isChecked = working.subtitlesEnabled
        binding.subtitlesSwitch.setOnCheckedChangeListener { _, checked ->
            working.subtitlesEnabled = checked
            refreshSubtitleVisibility()
        }
        binding.preferManualSubsCheckBox.isChecked = working.preferManualSubtitles
        binding.preferManualSubsCheckBox.setOnCheckedChangeListener { _, checked ->
            working.preferManualSubtitles = checked
        }
        binding.includeAutoSubsCheckBox.isChecked = working.includeAutoGenerated
        binding.includeAutoSubsCheckBox.setOnCheckedChangeListener { _, checked ->
            working.includeAutoGenerated = checked
        }

        binding.subtitleLanguagesContainer.removeAllViews()
        subtitleCheckBoxes.clear()
        for (code in PlaylistBatchResolver.commonSubtitleLanguages) {
            val checkBox = CheckBox(requireContext()).apply {
                text = PlaylistBatchResolver.languageDisplayName(code)
                isChecked = working.subtitleLanguages.contains(code)
            }
            subtitleCheckBoxes.add(checkBox)
            binding.subtitleLanguagesContainer.addView(checkBox)
        }
    }

    private fun setupNaming() {
        binding.subfolderCheckBox.isChecked = working.usePlaylistSubfolder
        binding.subfolderCheckBox.setOnCheckedChangeListener { _, checked ->
            working.usePlaylistSubfolder = checked
        }
        binding.templateInput.setText(working.filenameTemplate)
        binding.templateInput.setOnFocusChangeListener { _, hasFocus ->
            if (!hasFocus) {
                working.filenameTemplate = binding.templateInput.text?.toString().orEmpty()
                refreshPreview()
            }
        }
        binding.languageSuffixCheckBox.isChecked = working.appendLanguageSuffix
        binding.languageSuffixCheckBox.setOnCheckedChangeListener { _, checked ->
            working.appendLanguageSuffix = checked
            refreshPreview()
        }
    }

    private fun refreshSubtitleVisibility() {
        val visible = working.subtitlesEnabled
        binding.subtitleLanguagesLabel.visibility = if (visible) View.VISIBLE else View.GONE
        binding.subtitleLanguagesContainer.visibility = if (visible) View.VISIBLE else View.GONE
        binding.preferManualSubsCheckBox.visibility = if (visible) View.VISIBLE else View.GONE
        binding.includeAutoSubsCheckBox.visibility = if (visible) View.VISIBLE else View.GONE
    }

    private fun refreshPreview() {
        if (_binding == null || initializing) {
            return
        }
        working.filenameTemplate = binding.templateInput.text?.toString().orEmpty()
        val first = viewModel.firstSelectedItem()
        if (first == null) {
            binding.filenamePreviewView.text = getString(R.string.playlist_batch_preview_none)
            return
        }
        val total = maxOf(viewModel.selectedItems().size, 1)
        binding.filenamePreviewView.text = PlaylistBatchResolver.buildFileName(
            requireContext(),
            working.filenameTemplate,
            first,
            total,
            working.toImmutable(),
            viewModel.getOverride(first.url),
            audioLanguage = null
        )
    }

    private fun setSpinnerItems(
        spinner: Spinner,
        labels: List<String>,
        selected: Int,
        onSelected: (Int) -> Unit
    ) {
        spinner.adapter = ArrayAdapter(
            requireContext(),
            android.R.layout.simple_spinner_item,
            labels
        ).apply {
            setDropDownViewResource(android.R.layout.simple_spinner_dropdown_item)
        }
        spinner.setSelection(selected.coerceIn(0, labels.size - 1), false)
        spinner.onItemSelectedListener = object : AdapterView.OnItemSelectedListener {
            override fun onItemSelected(
                parent: AdapterView<*>?,
                view: View?,
                position: Int,
                id: Long
            ) {
                if (initializing) {
                    return
                }
                onSelected(position)
            }

            override fun onNothingSelected(parent: AdapterView<*>?) {
                // keep current selection
            }
        }
    }
}
