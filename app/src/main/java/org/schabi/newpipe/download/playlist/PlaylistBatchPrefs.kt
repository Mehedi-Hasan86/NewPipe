package org.schabi.newpipe.download.playlist

import android.content.Context
import androidx.preference.PreferenceManager
import org.schabi.newpipe.R

/**
 * Persists the last-used global [PlaylistDownloadOptions] in SharedPreferences
 * and restores them, following the existing `*_key` preference style.
 */
object PlaylistBatchPrefs {

    fun load(context: Context): PlaylistDownloadOptions {
        val prefs = PreferenceManager.getDefaultSharedPreferences(context)
        return PlaylistDownloadOptions(
            mode = readEnum(
                prefs.getString(context.getString(R.string.playlist_batch_mode_key), null),
                PlaylistBatchMode.VIDEO
            ),
            targetResolution = prefs.getString(
                context.getString(R.string.playlist_batch_resolution_key),
                PlaylistDownloadOptions.DEFAULT_TARGET_RESOLUTION
            ) ?: PlaylistDownloadOptions.DEFAULT_TARGET_RESOLUTION,
            videoContainer = readEnum(
                prefs.getString(
                    context.getString(R.string.playlist_batch_video_container_key),
                    null
                ),
                PlaylistVideoContainer.MP4
            ),
            fallbackToBest = prefs.getBoolean(
                context.getString(R.string.playlist_batch_fallback_best_key),
                true
            ),
            audioContainer = readEnum(
                prefs.getString(
                    context.getString(R.string.playlist_batch_audio_container_key),
                    null
                ),
                PlaylistAudioContainer.M4A
            ),
            preferHighestBitrate = prefs.getBoolean(
                context.getString(R.string.playlist_batch_audio_highest_bitrate_key),
                true
            ),
            subtitlesEnabled = prefs.getBoolean(
                context.getString(R.string.playlist_batch_subs_enabled_key),
                false
            ),
            subtitleLanguages = prefs.getStringSet(
                context.getString(R.string.playlist_batch_subs_languages_key),
                emptySet()
            ).orEmpty().toList().sorted(),
            preferManualSubtitles = prefs.getBoolean(
                context.getString(R.string.playlist_batch_subs_prefer_manual_key),
                true
            ),
            includeAutoGenerated = prefs.getBoolean(
                context.getString(R.string.playlist_batch_subs_include_auto_key),
                false
            ),
            preferredAudioLanguage = prefs.getString(
                context.getString(R.string.playlist_batch_audio_language_key),
                PlaylistDownloadOptions.AUDIO_LANGUAGE_ORIGINAL
            ) ?: PlaylistDownloadOptions.AUDIO_LANGUAGE_ORIGINAL,
            missingLanguageAction = readEnum(
                prefs.getString(
                    context.getString(R.string.playlist_batch_missing_language_action_key),
                    null
                ),
                MissingLanguageAction.USE_ORIGINAL
            ),
            usePlaylistSubfolder = prefs.getBoolean(
                context.getString(R.string.playlist_batch_subfolder_key),
                true
            ),
            filenameTemplate = prefs.getString(
                context.getString(R.string.playlist_batch_template_key),
                PlaylistDownloadOptions.DEFAULT_FILENAME_TEMPLATE
            ) ?: PlaylistDownloadOptions.DEFAULT_FILENAME_TEMPLATE,
            duplicateAction = readEnum(
                prefs.getString(
                    context.getString(R.string.playlist_batch_duplicate_action_key),
                    null
                ),
                DuplicateAction.OVERWRITE
            ),
            appendLanguageSuffix = prefs.getBoolean(
                context.getString(R.string.playlist_batch_language_suffix_key),
                true
            )
        )
    }

    fun save(context: Context, options: PlaylistDownloadOptions) {
        PreferenceManager.getDefaultSharedPreferences(context).edit()
            .putString(
                context.getString(R.string.playlist_batch_mode_key),
                options.mode.name
            )
            .putString(
                context.getString(R.string.playlist_batch_resolution_key),
                options.targetResolution
            )
            .putString(
                context.getString(R.string.playlist_batch_video_container_key),
                options.videoContainer.name
            )
            .putBoolean(
                context.getString(R.string.playlist_batch_fallback_best_key),
                options.fallbackToBest
            )
            .putString(
                context.getString(R.string.playlist_batch_audio_container_key),
                options.audioContainer.name
            )
            .putBoolean(
                context.getString(R.string.playlist_batch_audio_highest_bitrate_key),
                options.preferHighestBitrate
            )
            .putBoolean(
                context.getString(R.string.playlist_batch_subs_enabled_key),
                options.subtitlesEnabled
            )
            .putStringSet(
                context.getString(R.string.playlist_batch_subs_languages_key),
                options.subtitleLanguages.toSet()
            )
            .putBoolean(
                context.getString(R.string.playlist_batch_subs_prefer_manual_key),
                options.preferManualSubtitles
            )
            .putBoolean(
                context.getString(R.string.playlist_batch_subs_include_auto_key),
                options.includeAutoGenerated
            )
            .putString(
                context.getString(R.string.playlist_batch_audio_language_key),
                options.preferredAudioLanguage
            )
            .putString(
                context.getString(R.string.playlist_batch_missing_language_action_key),
                options.missingLanguageAction.name
            )
            .putBoolean(
                context.getString(R.string.playlist_batch_subfolder_key),
                options.usePlaylistSubfolder
            )
            .putString(
                context.getString(R.string.playlist_batch_template_key),
                options.filenameTemplate
            )
            .putString(
                context.getString(R.string.playlist_batch_duplicate_action_key),
                options.duplicateAction.name
            )
            .putBoolean(
                context.getString(R.string.playlist_batch_language_suffix_key),
                options.appendLanguageSuffix
            )
            .apply()
    }

    private inline fun <reified T : Enum<T>> readEnum(raw: String?, fallback: T): T {
        if (raw.isNullOrBlank()) {
            return fallback
        }
        return enumValues<T>().firstOrNull { it.name == raw } ?: fallback
    }
}
