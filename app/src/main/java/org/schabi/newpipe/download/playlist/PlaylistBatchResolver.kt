/**
 * Small shared helpers for playlist batch download, reusing the existing
 * [ListHelper], [Localization] and [FilenameUtils] logic instead of copying it.
 *
 * Final per-item stream picking (resolution/format/bitrate) happens in STEP 3;
 * these helpers only expose what STEP 2's options UI needs.
 */
object PlaylistBatchResolver {

    /** One audio track group (same track id), as shown in the language dropdown. */
    data class AudioTrackChoice(
        /** Null means a single default track (see [StreamInfo] without track ids). */
        val trackId: String?,
        val displayName: String,
        /** ISO 639-1 code, e.g. "hi", or null when unknown. */
        val languageCode: String?,
        /** Track type name (ORIGINAL/DUBBED/…), or null when unknown. */
        val trackType: String? = null
    )

    /** One subtitle option, as shown in the per-item UI. */
    data class SubtitleChoice(
        val languageTag: String,
        val displayName: String,
        val autoGenerated: Boolean
    )

    /** Curated ISO 639-1 codes offered in the global subtitle multi-select. */
    val commonSubtitleLanguages: List<String> = listOf(
        "en", "es", "hi", "pt", "ar", "fr", "de", "ru", "ja", "ko", "zh",
        "it", "nl", "tr", "pl", "uk", "vi", "th", "id", "ms", "ta", "te",
        "bn", "mr"
    )

    /** Curated ISO 639-1 codes offered as preferred audio language. */
    val commonAudioLanguages: List<String> = listOf(
        "en", "es", "hi", "pt", "fr", "de", "ru", "ja", "ar", "it", "ko",
        "tr", "pl", "uk", "ta", "te"
    )

    /**
     * Groups of audio tracks of [info], reusing [ListHelper.getGroupedAudioStreams].
     * A null [AudioTrackChoice.trackId] (or a single group) means a single default
     * track, for which the UI shows no language selector.
     */
    fun audioTrackChoices(context: Context, info: StreamInfo): List<AudioTrackChoice> {
        val streams = ListHelper.getStreamsOfSpecifiedDelivery(
            info.audioStreams,
            DeliveryMethod.PROGRESSIVE_HTTP
        )
        val grouped = ListHelper.getGroupedAudioStreams(context, streams)
        if (grouped.isEmpty()) {
            return emptyList()
        }
        if (grouped.size == 1 && grouped[0].firstOrNull()?.audioTrackId == null) {
            return listOf(
                AudioTrackChoice(
                    trackId = null,
                    displayName = Localization.audioTrackName(context, grouped[0][0]),
                    languageCode = grouped[0][0].audioLocale?.language,
                    trackType = grouped[0][0].audioTrackType?.name
                )
            )
        }
        return grouped.mapNotNull { group ->
            val first = group.firstOrNull() ?: return@mapNotNull null
            AudioTrackChoice(
                trackId = first.audioTrackId,
                displayName = Localization.audioTrackName(context, first),
                languageCode = first.audioLocale?.language,
                trackType = first.audioTrackType?.name
            )
        }
    }

    /** Subtitle options of [info] (progressive delivery only, like DownloadDialog). */
    fun subtitleChoices(info: StreamInfo): List<SubtitleChoice> {
        val streams = ListHelper.getStreamsOfSpecifiedDelivery(
            info.subtitles,
            DeliveryMethod.PROGRESSIVE_HTTP
        )
        return streams.mapNotNull { stream ->
            val tag = stream.languageTag ?: return@mapNotNull null
            SubtitleChoice(
                languageTag = tag,
                displayName = stream.displayLanguageName ?: tag,
                autoGenerated = stream.isAutoGenerated
            )
        }
    }

    /**
     * Builds the final file name (without folder) for [item].
     *
     * Tokens: {index} (zero-padded, width from [totalCount]), {title}, {channel},
     * {date} (item upload date or today), {lang}. A " [lang]" suffix is appended
     * when [audioLanguage] is a non-original language and the option is enabled.
     * Names are sanitized with [FilenameUtils], like the single-download dialog.
     */
    fun buildFileName(
        context: Context,
        template: String,
        item: PlaylistBatchItem,
        totalCount: Int,
        options: PlaylistDownloadOptions,
        override: PerItemOverride?,
        audioLanguage: String?
    ): String {
        val digits = maxOf(totalCount.toString().length, 1)
        val index = item.position.toString().padStart(digits, '0')
        val title = FilenameUtils.createFilename(context, item.title)
        val channel = FilenameUtils.createFilename(context, item.uploaderName.orEmpty())
        val date = item.uploadDateText?.takeIf { it.isNotBlank() }
            ?: LocalDate.now().format(DateTimeFormatter.ISO_LOCAL_DATE)
        val lang = audioLanguage
            ?: override?.audioTrackLanguage
            ?: options.preferredAudioLanguage

        var base = template.ifBlank { PlaylistDownloadOptions.DEFAULT_FILENAME_TEMPLATE }
            .replace("{index}", index)
            .replace("{title}", title)
            .replace("{channel}", channel)
            .replace("{date}", date)
            .replace("{lang}", lang)
        base = FilenameUtils.createFilename(context, base)

        val langSuffix = if (options.appendLanguageSuffix &&
            lang.isNotBlank() &&
            !lang.equals(
                PlaylistDownloadOptions.AUDIO_LANGUAGE_ORIGINAL,
                ignoreCase = true
            )
        ) {
            " [$lang]"
        } else {
            ""
        }
        val suffix = if (options.mode == PlaylistBatchMode.AUDIO_ONLY) {
            options.audioContainer.fileSuffix()
        } else {
            override?.videoContainer?.fileSuffix() ?: options.videoContainer.fileSuffix()
        }
        // Providers reject display names with '!', en dashes or trailing dots/spaces, and a
        // title that already ends with the suffix must not be extended twice.
        var cleanBase = base.replace("!", "").replace("–", "-").trim().trimEnd('.', ' ')
        if (cleanBase.endsWith(suffix, ignoreCase = true)) {
            cleanBase = cleanBase.dropLast(suffix.length).trimEnd('.', ' ')
        }
        if (cleanBase.isBlank()) {
            cleanBase = index
        }
        return cleanBase + langSuffix + suffix
    }

    /** Display name of an ISO 639-1 code, e.g. "hi" -> "Hindi". */
    fun languageDisplayName(code: String): String {
        if (code.equals(
                PlaylistDownloadOptions.AUDIO_LANGUAGE_ORIGINAL,
                ignoreCase = true
            )
        ) {
            return code
        }
        return try {
            Locale.Builder().setLanguage(code).build()
                .getDisplayName(Locale.getDefault()).replaceFirstChar { it.uppercase() }
        } catch (e: Exception) {
            code
        }
    }

    // ------------------------------------------------------------------
    // Stream picking (used by the STEP 3 executor; mirrors DownloadDialog)
    // ------------------------------------------------------------------

    /** Picked video stream plus its mux pairing, if the video is video-only. */
    data class ResolvedVideo(
        val main: VideoStream,
        val secondaryAudio: AudioStream?,
        val postprocessingName: String?,
        val postprocessingArgs: Array<String>?
    )

    /** Audio picking outcome. */
    sealed class AudioResolution {
        data class Chosen(val stream: AudioStream) : AudioResolution()
        data object NoAudio : AudioResolution()
        data class MissingLanguage(val available: List<AudioTrackChoice>) : AudioResolution()
    }

    /**
     * Picks the video stream for [targetResolution] (e.g. "720p") in [container].
     * Prefers progressive streams (no muxing); falls back to video-only + muxed audio
     * via [SecondaryStreamHelper] like DownloadDialog. With [fallbackToBest] picks the
     * best stream at or below the target, else the best available; without it returns
     * null when nothing matches exactly.
     */
    fun resolveVideo(
        context: Context,
        info: StreamInfo,
        targetResolution: String,
        container: PlaylistVideoContainer,
        fallbackToBest: Boolean
    ): ResolvedVideo? {
        val format = if (container == PlaylistVideoContainer.MP4) {
            MediaFormat.MPEG_4
        } else {
            MediaFormat.WEBM
        }
        val candidates = ListHelper.getStreamsOfSpecifiedDelivery(
            info.videoStreams,
            DeliveryMethod.PROGRESSIVE_HTTP
        ).filter { it.format == format } +
            ListHelper.getStreamsOfSpecifiedDelivery(
                info.videoOnlyStreams,
                DeliveryMethod.PROGRESSIVE_HTTP
            ).filter { it.format == format }
        if (candidates.isEmpty()) {
            return null
        }

        val exact = candidates.filter { it.getResolution() == targetResolution }
        val main = exact.firstOrNull { !it.isVideoOnly }
            ?: exact.firstOrNull()
            ?: if (!fallbackToBest) {
                return null
            } else {
                pickBestBelow(candidates, targetResolution)
                    ?: candidates.maxByOrNull { resolutionHeight(it.getResolution()) }
            }
            ?: return null

        return if (main.isVideoOnly) {
            val audioStreams = ListHelper.getStreamsOfSpecifiedDelivery(
                info.audioStreams,
                DeliveryMethod.PROGRESSIVE_HTTP
            )
            val secondary = SecondaryStreamHelper.getAudioStreamFor(
                context,
                audioStreams,
                main
            ) ?: return null
            val psName = if (format == MediaFormat.MPEG_4) {
                Postprocessing.ALGORITHM_MP4_FROM_DASH_MUXER
            } else {
                Postprocessing.ALGORITHM_WEBM_MUXER
            }
            ResolvedVideo(main, secondary, psName, null)
        } else {
            ResolvedVideo(main, null, null, null)
        }
    }

    /**
     * Picks the audio stream: override track id first, then the preferred language,
     * then the default group from [ListHelper]. Returns [AudioResolution.MissingLanguage]
     * when a non-original language was requested but is unavailable, so the caller
     * can apply the configured fallback rule.
     */
    fun resolveAudio(
        context: Context,
        info: StreamInfo,
        container: PlaylistAudioContainer,
        preferHighestBitrate: Boolean,
        preferredLanguage: String,
        overrideTrackId: String?
    ): AudioResolution {
        val streams = ListHelper.getStreamsOfSpecifiedDelivery(
            info.audioStreams,
            DeliveryMethod.PROGRESSIVE_HTTP
        )
        val grouped = ListHelper.getGroupedAudioStreams(context, streams)
        if (grouped.isEmpty()) {
            return AudioResolution.NoAudio
        }
        if (grouped.size == 1 && grouped[0].firstOrNull()?.audioTrackId == null) {
            return pickFromGroup(grouped[0], container, preferHighestBitrate)
                ?.let { AudioResolution.Chosen(it) }
                ?: AudioResolution.NoAudio
        }

        overrideTrackId?.let { wanted ->
            grouped.firstOrNull { group ->
                group.any { it.audioTrackId == wanted }
            }?.let { group ->
                pickFromGroup(group, container, preferHighestBitrate)
                    ?.let { return AudioResolution.Chosen(it) }
            }
        }

        val wantOriginal = preferredLanguage.equals(
            PlaylistDownloadOptions.AUDIO_LANGUAGE_ORIGINAL,
            ignoreCase = true
        )
        if (wantOriginal) {
            val index = ListHelper.getDefaultAudioTrackGroup(context, grouped)
            if (index >= 0) {
                pickFromGroup(grouped[index], container, preferHighestBitrate)
                    ?.let { return AudioResolution.Chosen(it) }
            }
            return AudioResolution.NoAudio
        }

        grouped.firstOrNull { group ->
            group.firstOrNull()?.audioLocale?.language
                .equals(preferredLanguage, ignoreCase = true)
        }?.let { group ->
            pickFromGroup(group, container, preferHighestBitrate)
                ?.let { return AudioResolution.Chosen(it) }
        }
        return AudioResolution.MissingLanguage(audioTrackChoices(context, info))
    }

    /** Postprocessing algorithm for a picked audio stream, mirroring DownloadDialog. */
    fun audioPostprocessing(stream: AudioStream): String? {
        return when (stream.format) {
            MediaFormat.M4A -> Postprocessing.ALGORITHM_M4A_NO_DASH
            MediaFormat.WEBMA_OPUS -> Postprocessing.ALGORITHM_OGG_FROM_WEBM_DEMUXER
            else -> null
        }
    }

    /**
     * Best matching subtitle (manual preferred, auto-generated only when allowed).
     * Returns null when nothing matches; callers skip subtitles silently then.
     */
    fun resolveSubtitle(
        info: StreamInfo,
        languages: List<String>,
        preferManual: Boolean,
        includeAuto: Boolean
    ): SubtitlesStream? {
        if (languages.isEmpty()) {
            return null
        }
        val streams = ListHelper.getStreamsOfSpecifiedDelivery(
            info.subtitles,
            DeliveryMethod.PROGRESSIVE_HTTP
        ).filter { stream ->
            val tag = stream.languageTag ?: return@filter false
            languages.any { code ->
                tag.equals(code, ignoreCase = true) ||
                    tag.startsWith("$code-", ignoreCase = true)
            } && (includeAuto || !stream.isAutoGenerated)
        }
        if (streams.isEmpty()) {
            return null
        }
        if (preferManual) {
            streams.firstOrNull { !it.isAutoGenerated }?.let { return it }
        }
        return streams[0]
    }

    /** Postprocessing for a subtitle: TTML is converted to SRT, like DownloadDialog. */
    fun subtitlePostprocessing(stream: SubtitlesStream): Pair<String?, Array<String>?> {
        return if (stream.format == MediaFormat.TTML) {
            Pair(
                Postprocessing.ALGORITHM_TTML_CONVERTER,
                arrayOf(stream.format?.getSuffix() ?: "ttml", "false")
            )
        } else {
            Pair(null, null)
        }
    }

    private fun pickFromGroup(
        group: List<AudioStream>,
        container: PlaylistAudioContainer,
        preferHighestBitrate: Boolean
    ): AudioStream? {
        if (group.isEmpty()) {
            return null
        }
        val wanted = if (container == PlaylistAudioContainer.M4A) {
            MediaFormat.M4A
        } else {
            MediaFormat.WEBMA_OPUS
        }
        val inContainer = group.filter { it.format == wanted }
        val pool = inContainer.ifEmpty { group }
        return if (preferHighestBitrate) {
            pool.maxByOrNull { it.averageBitrate }
        } else {
            pool.minByOrNull { it.averageBitrate }
        }
    }

    private fun pickBestBelow(
        candidates: List<VideoStream>,
        targetResolution: String
    ): VideoStream? {
        val target = resolutionHeight(targetResolution)
        return candidates
            .filter { resolutionHeight(it.getResolution()) <= target }
            .maxByOrNull { resolutionHeight(it.getResolution()) }
    }

    private fun resolutionHeight(resolution: String?): Int {
        if (resolution.isNullOrBlank()) {
            return 0
        }
        return resolution.takeWhile { it.isDigit() }.toIntOrNull() ?: 0
    }
}
