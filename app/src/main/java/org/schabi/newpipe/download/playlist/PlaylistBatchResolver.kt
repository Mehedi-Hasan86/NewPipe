package org.schabi.newpipe.download.playlist

import android.content.Context
import java.time.LocalDate
import java.time.format.DateTimeFormatter
import java.util.Locale
import org.schabi.newpipe.extractor.stream.DeliveryMethod
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.util.FilenameUtils
import org.schabi.newpipe.util.ListHelper
import org.schabi.newpipe.util.Localization

/**
 * Small shared helpers for playlist batch download, reusing the existing
 * [ListHelper], [Localization] and [FilenameUtils] logic instead of copying it.
 *
 * Final per-item stream picking (resolution/format/bitrate) happens in STEP 3;
 * these helpers only expose what STEP 2's options UI needs.
 */
object PlaylistBatchResolver {

    /** One audio track group (same track id), as shown in the language dropdown. */
    data class AudioTrackChoice(
        /** Null means a single default track (see [StreamInfo] without track ids). */
        val trackId: String?,
        val displayName: String,
        /** ISO 639-1 code, e.g. "hi", or null when unknown. */
        val languageCode: String?
    )

    /** One subtitle option, as shown in the per-item UI. */
    data class SubtitleChoice(
        val languageTag: String,
        val displayName: String,
        val autoGenerated: Boolean
    )

    /** Curated ISO 639-1 codes offered in the global subtitle multi-select. */
    val commonSubtitleLanguages: List<String> = listOf(
        "en", "es", "hi", "pt", "ar", "fr", "de", "ru", "ja", "ko", "zh",
        "it", "nl", "tr", "pl", "uk", "vi", "th", "id", "ms", "ta", "te",
        "bn", "mr"
    )

    /** Curated ISO 639-1 codes offered as preferred audio language. */
    val commonAudioLanguages: List<String> = listOf(
        "en", "es", "hi", "pt", "fr", "de", "ru", "ja", "ar", "it", "ko",
        "tr", "pl", "uk", "ta", "te"
    )

    /**
     * Groups of audio tracks of [info], reusing [ListHelper.getGroupedAudioStreams].
     * A null [AudioTrackChoice.trackId] (or a single group) means a single default
     * track, for which the UI shows no language selector.
     */
    fun audioTrackChoices(context: Context, info: StreamInfo): List<AudioTrackChoice> {
        val streams = ListHelper.getStreamsOfSpecifiedDelivery(
            info.audioStreams,
            DeliveryMethod.PROGRESSIVE_HTTP
        )
        val grouped = ListHelper.getGroupedAudioStreams(context, streams)
        if (grouped.isEmpty()) {
            return emptyList()
        }
        if (grouped.size == 1 && grouped[0].firstOrNull()?.audioTrackId == null) {
            return listOf(
                AudioTrackChoice(
                    trackId = null,
                    displayName = Localization.audioTrackName(context, grouped[0][0]),
                    languageCode = grouped[0][0].audioLocale?.language
                )
            )
        }
        return grouped.mapNotNull { group ->
            val first = group.firstOrNull() ?: return@mapNotNull null
            AudioTrackChoice(
                trackId = first.audioTrackId,
                displayName = Localization.audioTrackName(context, first),
                languageCode = first.audioLocale?.language
            )
        }
    }

    /** Subtitle options of [info] (progressive delivery only, like DownloadDialog). */
    fun subtitleChoices(info: StreamInfo): List<SubtitleChoice> {
        val streams = ListHelper.getStreamsOfSpecifiedDelivery(
            info.subtitles,
            DeliveryMethod.PROGRESSIVE_HTTP
        )
        return streams.mapNotNull { stream ->
            val tag = stream.languageTag ?: return@mapNotNull null
            SubtitleChoice(
                languageTag = tag,
                displayName = stream.displayLanguageName ?: tag,
                autoGenerated = stream.isAutoGenerated
            )
        }
    }

    /**
     * Builds the final file name (without folder) for [item].
     *
     * Tokens: {index} (zero-padded, width from [totalCount]), {title}, {channel},
     * {date} (item upload date or today), {lang}. A " [lang]" suffix is appended
     * when [audioLanguage] is a non-original language and the option is enabled.
     * Names are sanitized with [FilenameUtils], like the single-download dialog.
     */
    fun buildFileName(
        context: Context,
        template: String,
        item: PlaylistBatchItem,
        totalCount: Int,
        options: PlaylistDownloadOptions,
        override: PerItemOverride?,
        audioLanguage: String?
    ): String {
        val digits = maxOf(totalCount.toString().length, 1)
        val index = item.position.toString().padStart(digits, '0')
        val title = FilenameUtils.createFilename(context, item.title)
        val channel = FilenameUtils.createFilename(context, item.uploaderName.orEmpty())
        val date = item.uploadDateText?.takeIf { it.isNotBlank() }
            ?: LocalDate.now().format(DateTimeFormatter.ISO_LOCAL_DATE)
        val lang = audioLanguage
            ?: override?.audioTrackLanguage
            ?: options.preferredAudioLanguage

        var base = template.ifBlank { PlaylistDownloadOptions.DEFAULT_FILENAME_TEMPLATE }
            .replace("{index}", index)
            .replace("{title}", title)
            .replace("{channel}", channel)
            .replace("{date}", date)
            .replace("{lang}", lang)
        base = FilenameUtils.createFilename(context, base)

        val langSuffix = if (options.appendLanguageSuffix &&
            lang.isNotBlank() &&
            !lang.equals(
                PlaylistDownloadOptions.AUDIO_LANGUAGE_ORIGINAL,
                ignoreCase = true
            )
        ) {
            " [$lang]"
        } else {
            ""
        }
        val suffix = if (options.mode == PlaylistBatchMode.AUDIO_ONLY) {
            options.audioContainer.fileSuffix()
        } else {
            override?.videoContainer?.fileSuffix() ?: options.videoContainer.fileSuffix()
        }
        return base + langSuffix + suffix
    }

    /** Display name of an ISO 639-1 code, e.g. "hi" -> "Hindi". */
    fun languageDisplayName(code: String): String {
        if (code.equals(
                PlaylistDownloadOptions.AUDIO_LANGUAGE_ORIGINAL,
                ignoreCase = true
            )
        ) {
            return code
        }
        return try {
            Locale.Builder().setLanguage(code).build()
                .getDisplayName(Locale.getDefault()).replaceFirstChar { it.uppercase() }
        } catch (e: Exception) {
            code
        }
    }
}
